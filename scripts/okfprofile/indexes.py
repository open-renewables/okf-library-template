"""Generated ``index.md`` files (SDD I-07, SRS FR4).

Every folder of the bundle that holds concepts gets an index with one line per subfolder and per concept, so an
agent can navigate one level at a time. Indexes are written only by this module, never by hand. Links are
relative (ADR-005).
"""

from __future__ import annotations

import posixpath
from pathlib import Path
from urllib.parse import quote

from okfprofile.config import Profile
from okfprofile.document import Concept
from okfprofile.history import history_lines
from okfprofile.revision import concept_tier

HEADER = "<!-- Generated by build_indexes.py. Do not edit. -->"
INDEX = "index.md"


def humanise(name: str) -> str:
    """A display title from a folder or file name: hyphens become spaces, first letter capital."""
    words = name.replace("-", " ")
    return words[:1].upper() + words[1:]


def _link(text: str, target: str) -> str:
    label = text.replace("[", "\\[").replace("]", "\\]")
    return f"[{label}]({quote(target, safe='/-_.~')})"


def _title(concept: Concept) -> str:
    title = (concept.frontmatter or {}).get("title")
    return title if isinstance(title, str) and title else humanise(concept.concept_id.rsplit("/", 1)[-1])


def _line(profile: Profile, concept: Concept, folder: str) -> str:
    name = posixpath.relpath(f"{concept.concept_id}.md", folder or ".")
    parts = []
    description = (concept.frontmatter or {}).get("description")
    if isinstance(description, str) and description.strip():
        parts.append(" ".join(description.split()))
    status = (concept.frontmatter or {}).get("status")
    if profile.index.show_status and isinstance(status, str):
        parts.append(status)
    if profile.index.show_tier:
        lines = history_lines(profile, concept)
        parts.append(concept_tier(lines, profile.rules.require_non_author_approver).label)
    head = f"- {_link(_title(concept), name)}"
    return f"{head} — {' · '.join(parts)}" if parts else head


def _folder_of(concept: Concept) -> str:
    return posixpath.dirname(concept.concept_id)


def folders_of(concepts: list[Concept]) -> set[str]:
    """Every folder (root is the empty string) that holds a concept directly or through a subfolder."""
    folders: set[str] = set()
    for concept in concepts:
        folder = _folder_of(concept)
        while True:
            folders.add(folder)
            if not folder:
                break
            folder = posixpath.dirname(folder)
    return folders


def _text(profile: Profile, folder: str, concepts: list[Concept], folders: set[str]) -> str:
    own = sorted((c for c in concepts if _folder_of(c) == folder), key=lambda c: (_title(c).casefold(), c.concept_id))
    children = sorted(
        (f for f in folders if f and posixpath.dirname(f) == folder),
        key=lambda f: (humanise(posixpath.basename(f)).casefold(), f),
    )
    heading = humanise(posixpath.basename(folder)) if folder else profile.library_title
    lines = [HEADER, f"# {heading}"]
    if children:
        lines += ["", "## Folders", ""]
        for child in children:
            target = posixpath.relpath(f"{child}/{INDEX}", folder or ".")
            lines.append(f"- {_link(humanise(posixpath.basename(child)), target)}")
    if own:
        lines += ["", "## Concepts", ""]
        lines += [_line(profile, concept, folder) for concept in own]
    body = "\n".join(lines) + "\n"
    if folder:
        return body
    return f'---\nokf_version: "{profile.okf_version}"\n---\n\n{body}'


def expected_indexes(profile: Profile, concepts: list[Concept]) -> dict[str, str]:
    """The text of every index the bundle should have.

    Args:
        profile: The loaded profile.
        concepts: Every concept of the bundle.

    Returns:
        Index text by path relative to the bundle root, with LF line endings. Empty if there are no concepts.
    """
    folders = folders_of(concepts)
    return {posixpath.join(folder, INDEX): _text(profile, folder, concepts, folders) for folder in sorted(folders)}


def write_indexes(
    profile: Profile, concepts: list[Concept], only_folders: set[str] | None = None, only_missing: bool = False
) -> list[Path]:
    """Write the bundle's indexes.

    Args:
        profile: The loaded profile.
        concepts: Every concept of the bundle.
        only_folders: Write just these folders' indexes (root is the empty string); None writes all of them.
        only_missing: Leave an index that already exists untouched.

    Returns:
        The paths written.
    """
    written = []
    for relative, text in expected_indexes(profile, concepts).items():
        folder = posixpath.dirname(relative)
        target = profile.bundle_root / relative
        if only_folders is not None and folder not in only_folders:
            continue
        if only_missing and target.exists():
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        written.append(target)
    return written


def unexpected_indexes(profile: Profile, concepts: list[Concept]) -> list[str]:
    """Index files in folders that hold no concept, as paths relative to the bundle root."""
    expected = set(expected_indexes(profile, concepts))
    found = {p.relative_to(profile.bundle_root).as_posix() for p in profile.bundle_root.rglob(INDEX)}
    return sorted(found - expected)
