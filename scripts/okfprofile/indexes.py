"""Generated ``index.md`` files (SDD I-07, SRS FR4).

Every folder of the bundle that holds concepts gets an index with one line per subfolder and per concept, so an
agent can navigate one level at a time. Indexes are written only by this module, never by hand. Links are
relative (ADR-005).

The one exception is an optional YAML header on a folder's index whose ``description`` is the folder's scope, one
sentence (ADR-010). The generator keeps the header as written, rewrites the body, and puts the description on the
folder's line in the parent index. The root index's header is bundle metadata under OKF v0.3 §8.1:
``okf_version``, ``title``, ``description``, ``license`` and extension keys, all kept as written; only
``okf_version`` is rewritten when it differs from the profile's (RFC-002, ADR-013).
"""

from __future__ import annotations

import posixpath
import re
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import quote

from ruamel.yaml.error import YAMLError

from okfprofile.config import Profile
from okfprofile.document import Concept, KeyPath, parse_yaml
from okfprofile.history import history_lines
from okfprofile.revision import concept_tier

HEADER = "<!-- Generated by build_indexes.py. Do not edit. -->"
INDEX = "index.md"
DELIMITER = "---"
OKF_VERSION_LINE = re.compile(r"^okf_version\s*:")
FOLDER_KEYS = frozenset({"description"})
ROOT_LINE_KEYS = ("title", "description")


@dataclass(frozen=True)
class IndexHeader:
    """The YAML header found at the top of an existing ``index.md`` (ADR-010).

    Attributes:
        raw: The header block as written, from the opening to the closing ``---`` with a final newline; None when
            the index has no header.
        values: The parsed mapping; None when there is no header or it does not parse.
        problem: ``(code, line, message)`` when the header is not usable: ``OKF505`` (not closed, not YAML, not a
            mapping) or ``OKF506`` (a key that is not allowed, or a description that is not one line of text).
    """

    raw: str | None = None
    values: dict[str, object] | None = None
    problem: tuple[str, int, str] | None = None

    @property
    def description(self) -> str | None:
        """The folder's scope sentence, or None when absent or the header has a problem."""
        if self.problem is not None or not self.values:
            return None
        value = self.values.get("description")
        return value if isinstance(value, str) else None


def read_header(text: str, root: bool) -> IndexHeader:
    """Read the optional YAML header of an index.

    Args:
        text: The index file's text.
        root: True for the bundle's root index, which may carry any key (OKF v0.3 §8.1); its ``title`` and
            ``description`` must be one line of text and its ``license`` a non-empty string.

    Returns:
        The header, with ``problem`` set when it cannot be used.
    """
    lines = text.replace("\r\n", "\n").split("\n")
    if not lines or lines[0].rstrip() != DELIMITER:
        return IndexHeader()
    close = next((i for i in range(1, len(lines)) if lines[i].rstrip() == DELIMITER), None)
    if close is None:
        return IndexHeader(problem=("OKF505", 1, "the index header is not closed with '---'"))
    raw = "\n".join(lines[: close + 1]) + "\n"
    try:
        value, key_lines = parse_yaml("\n".join(lines[1:close]))
    except YAMLError as exc:
        mark = getattr(exc, "problem_mark", None)
        line = mark.line + 2 if mark is not None else 1
        return IndexHeader(raw=raw, problem=("OKF505", line, f"the index header is not valid YAML: {exc}"))
    if not isinstance(value, dict):
        return IndexHeader(raw=raw, problem=("OKF505", 2, "the index header must be a YAML mapping"))
    return IndexHeader(raw, value, _key_problem(value, key_lines, root))


def _key_problem(value: dict[str, object], key_lines: dict[KeyPath, int], root: bool) -> tuple[str, int, str] | None:
    """``OKF506`` for a key a header may not hold, or a value of the wrong shape; None when the header is usable."""

    def at(key: str) -> int:
        return key_lines.get((key,), 0) + 2

    if not root:
        for key in value:
            if key not in FOLDER_KEYS:
                return ("OKF506", at(key), f"'{key}' is not allowed; a folder index header holds 'description' only")
    for key in ROOT_LINE_KEYS if root else ("description",):
        text = value.get(key)
        if key in value and (not isinstance(text, str) or not text.strip() or "\n" in text.strip()):
            return ("OKF506", at(key), f"the {key} must be one line of text")
    licence = value.get("license")
    if root and "license" in value and (not isinstance(licence, str) or not licence.strip()):
        return ("OKF506", at("license"), "the license must be an SPDX expression or a file path")
    return None


def _read_header_file(file: Path, root: bool) -> IndexHeader:
    if not file.is_file():
        return IndexHeader()
    return read_header(file.read_bytes().decode("utf-8", errors="replace"), root)


def index_headers(profile: Profile, folders: set[str]) -> dict[str, IndexHeader]:
    """The header of each folder's existing index (root is the empty string)."""
    return {f: _read_header_file(profile.bundle_root / posixpath.join(f, INDEX), not f) for f in folders}


def humanise(name: str) -> str:
    """A display title from a folder or file name: hyphens become spaces, first letter capital."""
    words = name.replace("-", " ")
    return words[:1].upper() + words[1:]


def _link(text: str, target: str) -> str:
    label = text.replace("[", "\\[").replace("]", "\\]")
    return f"[{label}]({quote(target, safe='/-_.~')})"


def _title(concept: Concept) -> str:
    title = (concept.frontmatter or {}).get("title")
    return title if isinstance(title, str) and title else humanise(concept.concept_id.rsplit("/", 1)[-1])


def _line(profile: Profile, concept: Concept, folder: str) -> str:
    name = posixpath.relpath(f"{concept.concept_id}.md", folder or ".")
    parts = []
    description = (concept.frontmatter or {}).get("description")
    if isinstance(description, str) and description.strip():
        parts.append(" ".join(description.split()))
    status = (concept.frontmatter or {}).get("status")
    if profile.index.show_status and isinstance(status, str):
        parts.append(status)
    if profile.index.show_tier:
        lines = history_lines(profile, concept)
        parts.append(concept_tier(lines, profile.rules.require_non_author_approver).label)
    head = f"- {_link(_title(concept), name)}"
    return f"{head} — {' · '.join(parts)}" if parts else head


def _folder_of(concept: Concept) -> str:
    return posixpath.dirname(concept.concept_id)


def folders_of(concepts: list[Concept]) -> set[str]:
    """Every folder (root is the empty string) that holds a concept directly or through a subfolder."""
    folders: set[str] = set()
    for concept in concepts:
        folder = _folder_of(concept)
        while True:
            folders.add(folder)
            if not folder:
                break
            folder = posixpath.dirname(folder)
    return folders


def _root_header(profile: Profile, header: IndexHeader) -> str:
    """The root index header: kept as written, with only ``okf_version`` set to the profile's (OKF v0.3 §8.1)."""
    version_line = f'okf_version: "{profile.okf_version}"'
    if header.raw is None:
        return f"{DELIMITER}\n{version_line}\n{DELIMITER}\n"
    if header.problem is not None or header.values is None:
        return header.raw
    if str(header.values.get("okf_version")) == profile.okf_version:
        return header.raw
    lines = header.raw.split("\n")
    for index, line in enumerate(lines[1:-2], start=1):
        if OKF_VERSION_LINE.match(line):
            lines[index] = version_line
            return "\n".join(lines)
    return "\n".join([lines[0], version_line, *lines[1:]])


def _text(
    profile: Profile, folder: str, concepts: list[Concept], folders: set[str], headers: dict[str, IndexHeader]
) -> str:
    own = sorted((c for c in concepts if _folder_of(c) == folder), key=lambda c: (_title(c).casefold(), c.concept_id))
    children = sorted(
        (f for f in folders if f and posixpath.dirname(f) == folder),
        key=lambda f: (humanise(posixpath.basename(f)).casefold(), f),
    )
    heading = humanise(posixpath.basename(folder)) if folder else profile.library_title
    lines = [HEADER, f"# {heading}"]
    if children:
        lines += ["", "## Folders", ""]
        for child in children:
            target = posixpath.relpath(f"{child}/{INDEX}", folder or ".")
            line = f"- {_link(humanise(posixpath.basename(child)), target)}"
            scope = headers[child].description if child in headers else None
            lines.append(f"{line} — {' '.join(scope.split())}" if scope else line)
    if own:
        lines += ["", "## Concepts", ""]
        lines += [_line(profile, concept, folder) for concept in own]
    body = "\n".join(lines) + "\n"
    header = headers.get(folder, IndexHeader())
    if folder:
        return f"{header.raw}\n{body}" if header.raw is not None else body
    return f"{_root_header(profile, header)}\n{body}"


def expected_indexes(profile: Profile, concepts: list[Concept]) -> dict[str, str]:
    """The text of every index the bundle should have.

    An existing index's header is input, not output: it is kept as written (ADR-010), except that a root header
    whose ``okf_version`` differs from the profile's is rewritten.

    Args:
        profile: The loaded profile.
        concepts: Every concept of the bundle.

    Returns:
        Index text by path relative to the bundle root, with LF line endings. Empty if there are no concepts.
    """
    folders = folders_of(concepts)
    headers = index_headers(profile, folders)
    return {
        posixpath.join(folder, INDEX): _text(profile, folder, concepts, folders, headers) for folder in sorted(folders)
    }


def write_indexes(
    profile: Profile, concepts: list[Concept], only_folders: set[str] | None = None, only_missing: bool = False
) -> list[Path]:
    """Write the bundle's indexes.

    Args:
        profile: The loaded profile.
        concepts: Every concept of the bundle.
        only_folders: Write just these folders' indexes (root is the empty string); None writes all of them.
        only_missing: Leave an index that already exists untouched.

    Returns:
        The paths written.
    """
    written = []
    for relative, text in expected_indexes(profile, concepts).items():
        folder = posixpath.dirname(relative)
        target = profile.bundle_root / relative
        if only_folders is not None and folder not in only_folders:
            continue
        if only_missing and target.exists():
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        written.append(target)
    return written


def unexpected_indexes(profile: Profile, concepts: list[Concept]) -> list[str]:
    """Index files in folders that hold no concept, as paths relative to the bundle root."""
    expected = set(expected_indexes(profile, concepts))
    found = {p.relative_to(profile.bundle_root).as_posix() for p in profile.bundle_root.rglob(INDEX)}
    return sorted(found - expected)
