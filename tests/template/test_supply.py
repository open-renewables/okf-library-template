"""The hash-locked export and the audit command (plan step 2, NFR6, NFR7)."""

import shutil
from pathlib import Path

import pytest
from okfprofile import supply_cli
from okfprofile.supply_cli import EXPORTS, audit_command, audit_main, export_main, export_text
from support import ROOT

needs_uv = pytest.mark.skipif(shutil.which("uv") is None, reason="uv is not installed")


@pytest.fixture
def scratch(tmp_path: Path) -> Path:
    """A scratch tree with this repository's project file, lock and constraints."""
    for name in ("pyproject.toml", "uv.lock", ".python-version", "docs/development/constraints.md"):
        (tmp_path / name).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / name, tmp_path / name)
    return tmp_path


@needs_uv
def test_the_committed_files_match_the_lock() -> None:
    assert export_main(["--root", str(ROOT), "--check"]) == 0


@needs_uv
def test_every_package_is_hashed_and_the_header_is_stable() -> None:
    text = export_text(ROOT, "requirements/validate.txt")
    assert text.startswith("# Exported from uv.lock by scripts/export_requirements.py. Do not edit.\n")
    assert "autogenerated" not in text
    assert "\r" not in text
    requirement_lines = [line for line in text.splitlines() if "==" in line and not line.startswith("#")]
    assert requirement_lines
    assert text.count("--hash=sha256:") >= len(requirement_lines)
    assert "pytest==" not in text
    assert "pytest==" in export_text(ROOT, "requirements/dev.txt")


@needs_uv
def test_a_stale_file_fails_the_check_and_is_rewritten(scratch: Path) -> None:
    assert export_main(["--root", str(scratch), "--check"]) == 1
    assert export_main(["--root", str(scratch)]) == 0
    assert set(EXPORTS) == {p.relative_to(scratch).as_posix() for p in (scratch / "requirements").glob("*.txt")}
    assert export_main(["--root", str(scratch), "--check"]) == 0
    (scratch / "requirements" / "validate.txt").write_text("hand edit\n", encoding="utf-8")
    assert export_main(["--root", str(scratch), "--check"]) == 1


def test_a_failing_export_is_a_usage_error(tmp_path: Path) -> None:
    assert export_main(["--root", str(tmp_path), "--check"]) == 2


def test_the_audit_command_carries_recorded_exceptions(scratch: Path) -> None:
    assert audit_command(scratch) == ["uvx", "pip-audit", "--disable-pip", "--no-deps", "-r", "requirements/dev.txt"]
    constraints = scratch / "docs" / "development" / "constraints.md"
    text = constraints.read_text(encoding="utf-8").replace(
        "| — | — | None recorded | — |", "| PYSEC-1 | x | y | 2027-01-01 |"
    )
    constraints.write_text(text, encoding="utf-8", newline="\n")
    assert audit_command(scratch)[-2:] == ["--ignore-vuln", "PYSEC-1"]


def test_audit_main_prints_or_refuses(
    scratch: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    assert audit_main(["--root", str(scratch), "--print-command"]) == 0
    assert capsys.readouterr().out.startswith("uvx pip-audit")
    monkeypatch.setattr(supply_cli.shutil, "which", lambda _name: None)
    assert audit_main(["--root", str(scratch)]) == 2
    assert audit_main(["--root", str(scratch / "missing")]) == 2
